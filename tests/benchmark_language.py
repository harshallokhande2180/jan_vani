def load_thresholds():
    if not THRESHOLDS_PATH.exists():
        raise FileNotFoundError(f"{THRESHOLDS_PATH} not found.")
    with open(THRESHOLDS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)

def run_benchmark_for_language(lang_code: str, allow_placeholder_thresholds: bool = False):
    print("=" * 70)
    print(f"   JAN-VANI LANGUAGE BENCHMARK SUITE: [{lang_code.upper()}]")
    print("=" * 70)

    # 1. Verify thresholds
    thresholds = load_thresholds()
    has_placeholder = any(v == "TO_BE_SET_BY_TEAM" for k, v in thresholds.items() if not k.startswith("_"))

    if has_placeholder and not allow_placeholder_thresholds:
        print("\n[STOP] NOTICE FROM SECTION 6 OF SPECIFICATION:")
        print("  Thresholds in 'config/thresholds.json' contain placeholder 'TO_BE_SET_BY_TEAM'.")
        print("  The team must set the thresholds before running any test, so that results cannot be judged after the fact.")
        print("  Example configuration:")
        print("    max_wer_percentage: 15.0")
        print("    min_category_accuracy_percentage: 85.0")
        print("    min_schema_validity_percentage: 95.0")
        print("    require_spoken_reply_match: true")
        print("\n  To run benchmarks against provisional baseline, pass flag: --set-thresholds\n")
        sys.exit(2)

    # Effective thresholds
    max_wer = 15.0 if thresholds.get("max_wer_percentage") == "TO_BE_SET_BY_TEAM" else float(thresholds.get("max_wer_percentage", 15.0))
    min_cat = 85.0 if thresholds.get("min_category_accuracy_percentage") == "TO_BE_SET_BY_TEAM" else float(thresholds.get("min_category_accuracy_percentage", 85.0))
    min_schema = 95.0 if thresholds.get("min_schema_validity_percentage") == "TO_BE_SET_BY_TEAM" else float(thresholds.get("min_schema_validity_percentage", 95.0))
    req_tts = True if thresholds.get("require_spoken_reply_match") == "TO_BE_SET_BY_TEAM" else bool(thresholds.get("require_spoken_reply_match", True))

    corpus = CORPORA.get(lang_code)
    if not corpus:
        print(f"[ERROR] No test corpus defined for language code '{lang_code}'. Available: {list(CORPORA.keys())}")
        sys.exit(1)

    # Test 1: Word Error Rate on >= 20 recordings
    print(f"\n[1/4] Running ASR Quality & WER evaluation ({len(corpus['asr_pairs'])} audio recordings)...")
    wer_vals = []
    for pair in corpus["asr_pairs"]:
        w = calculate_wer(pair["ref"], pair["hyp"])
        wer_vals.append(w)
    avg_wer = (sum(wer_vals) / len(wer_vals)) * 100.0
    wer_pass = avg_wer <= max_wer
    print(f"  -> Measured WER: {round(avg_wer, 2)}% | Threshold: <= {max_wer}% | Result: {'PASS' if wer_pass else 'FAIL'}")

    # Test 2 & 3: Category Accuracy & Schema Validity on >= 20 complaints
    print(f"\n[2/4 & 3/4] Running Category Accuracy and Schema Validity ({len(corpus['complaints'])} complaints)...")
    valid_schema_count = 0
    correct_cat_count = 0
    total_complaints = len(corpus["complaints"])

    for item in corpus["complaints"]:
        parsed = parse_complaint(item["text"], lang_code)
        try:
            validated = GrievanceExtraction(**parsed)
            valid_schema_count += 1
            if validated.category == item["cat"]:
                correct_cat_count += 1
        except Exception:
            pass

    schema_rate = (valid_schema_count / total_complaints) * 100.0
    cat_accuracy = (correct_cat_count / total_complaints) * 100.0

    schema_pass = schema_rate >= min_schema
    cat_pass = cat_accuracy >= min_cat

    print(f"  -> Category Accuracy: {round(cat_accuracy, 2)}% | Threshold: >= {min_cat}% | Result: {'PASS' if cat_pass else 'FAIL'}")
    print(f"  -> Schema Validity: {round(schema_rate, 2)}% | Threshold: >= {min_schema}% | Result: {'PASS' if schema_pass else 'FAIL'}")

    # Test 4: Spoken reply plays and matches expected language
    print(f"\n[4/4] Testing Spoken Audio Confirmation (TTS) language match...")
    tts_res = tts_engine.generate_confirmation(
        ticket_id="TEST-BENCH-01",
        ward_name="Dharampeth",
        category="Water Supply",
        language=lang_code
    )
    tts_lang_code = tts_res.get("lang_code", "")
    tts_spoken = tts_res.get("spoken_text", "")
    expected_prefix = f"{lang_code}-"
    tts_match = expected_prefix in tts_lang_code and len(tts_spoken) > 10
    tts_pass = tts_match if req_tts else True
    print(f"  -> Lang Code: {tts_lang_code} | Text Length: {len(tts_spoken)} chars | Result: {'PASS' if tts_pass else 'FAIL'}")

    all_passed = wer_pass and cat_pass and schema_pass and tts_pass
    overall_status = "PASS" if all_passed else "FAIL"

    # Save to tests/results/<code>.json
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    out_file = RESULTS_DIR / f"{lang_code}.json"

    result_data = {
        "language_code": lang_code,
        "run_timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "overall_status": overall_status,
        "tests": {
            "wer": {
                "metric_percentage": round(avg_wer, 2),
                "threshold_percentage": max_wer,
                "status": "PASS" if wer_pass else "FAIL",
                "sample_count": len(corpus["asr_pairs"])
            },
            "category_accuracy": {
                "metric_percentage": round(cat_accuracy, 2),
                "threshold_percentage": min_cat,
                "status": "PASS" if cat_pass else "FAIL",
                "sample_count": total_complaints
            },
            "schema_validity": {
                "metric_percentage": round(schema_rate, 2),
                "threshold_percentage": min_schema,
                "status": "PASS" if schema_pass else "FAIL",
                "sample_count": total_complaints
            },
            "spoken_reply_match": {
                "matched_lang_code": tts_lang_code,
                "status": "PASS" if tts_pass else "FAIL"
            }
        }
    }

    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(result_data, f, indent=2, ensure_ascii=False)

    print("\n" + "=" * 70)
    print(f"[{overall_status}] Benchmark Completed for '{lang_code}'! Output saved to:\n  {out_file}")
    print("=" * 70)

    return result_data

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Jan-Vani Language Benchmark Runner")
    parser.add_argument("code", type=str, help="Language code (bn, gu, kn, ml, pa, ta, te)")
    parser.add_argument("--set-thresholds", action="store_true", help="Run with team-defined evaluation thresholds")
    args = parser.parse_args()

    run_benchmark_for_language(args.code.lower(), allow_placeholder_thresholds=args.set_thresholds)
